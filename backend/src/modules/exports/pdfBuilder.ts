/**
 * backend/src/modules/exports/pdfBuilder.ts
 *
 * Generates PDF documents using pdfkit strictly according to Phase 7 specifications:
 * 1. Media Preparation Record
 * 2. Autoclave Log Book (Sterilization)
 * 3. Combined Monthly Package (Continuous pagination across both parts)
 *
 * Formatting:
 * - A4 Landscape, 595.28 x 841.89 points
 * - Repeated headers on every page, page numbers ("Page X of Y")
 * - Text wrapping without clipping
 * - Disclaimers and blank signature lines
 */

import PDFDocument from "pdfkit";
import { MediaExportRow, AutoclaveExportRow, EquipmentExportInfo } from "./types";

interface ExportMetadata {
  reportingMonth: string;
  generatedBy: string;
  generatedAt: string;
}

/**
 * Builds Media Preparation Record PDF stream.
 */
export function buildMediaPdf(
  doc: PDFKit.PDFDocument,
  rows: MediaExportRow[],
  meta: ExportMetadata
): void {
  const pageWidth = 841.89; // A4 Landscape
  const pageHeight = 595.28;
  const leftMargin = 30;
  const topMargin = 30;
  const rightMargin = 30;
  const bottomMargin = 40;
  const contentWidth = pageWidth - leftMargin - rightMargin;

  // Header function
  const renderHeader = () => {
    doc
      .fontSize(13)
      .font("Helvetica-Bold")
      .fillColor("#111827")
      .text("PETLAD MAHAL AROGYA MANDAL PHARMACY", leftMargin, topMargin, {
        align: "center",
        width: contentWidth,
      });

    doc
      .fontSize(9)
      .font("Helvetica")
      .fillColor("#4B5563")
      .text(
        "At & Po. Village- Piplata- 387355, Ta.: Nadiad, Dist.: Kheda (Gujarat)",
        leftMargin,
        topMargin + 16,
        { align: "center", width: contentWidth }
      );

    doc
      .fontSize(11)
      .font("Helvetica-Bold")
      .fillColor("#1E40AF")
      .text(`Media Preparation Record — ${meta.reportingMonth}`, leftMargin, topMargin + 30, {
        align: "center",
        width: contentWidth,
      });
  };

  // Table Column Definitions
  const colWidths = [60, 160, 68, 68, 68, 55, 175, 80, 47];
  const colHeaders = [
    "Date",
    "Name of Media",
    "Opening (gm)",
    "Qty Used (gm)",
    "Balance (gm)",
    "Tube/Plates",
    "Used in",
    "Prepared by",
    "Status",
  ];

  const renderTableHeaders = (y: number) => {
    doc.rect(leftMargin, y, contentWidth, 20).fill("#2563EB");
    let currentX = leftMargin;
    doc.fontSize(8).font("Helvetica-Bold").fillColor("#FFFFFF");
    colHeaders.forEach((title, idx) => {
      const w = colWidths[idx];
      doc.text(title, currentX + 2, y + 5, {
        width: w - 4,
        align: idx >= 2 && idx <= 5 ? "right" : "left",
      });
      currentX += w;
    });
  };

  renderHeader();
  let currentY = topMargin + 50;
  renderTableHeaders(currentY);
  currentY += 20;

  // Render rows
  rows.forEach((r) => {
    if (currentY > pageHeight - bottomMargin - 40) {
      doc.addPage({ size: "A4", layout: "landscape" });
      renderHeader();
      currentY = topMargin + 50;
      renderTableHeaders(currentY);
      currentY += 20;
    }

    const rowHeight = 18;
    doc.rect(leftMargin, currentY, contentWidth, rowHeight).strokeColor("#E5E7EB").stroke();

    let currentX = leftMargin;
    const values = [
      r.date,
      r.mediaName,
      r.openingBalanceGm !== null ? r.openingBalanceGm.toFixed(2) : "—",
      r.quantityUsedGm !== null ? r.quantityUsedGm.toFixed(2) : "—",
      r.balanceGm !== null ? r.balanceGm.toFixed(2) : "—",
      String(r.tubePlates),
      r.usedIn,
      r.preparedBy,
      r.isBlocked ? "Blocked" : "",
    ];

    doc.fontSize(7.5).font("Helvetica").fillColor("#1F2937");
    values.forEach((val, idx) => {
      const w = colWidths[idx];
      const align = idx >= 2 && idx <= 5 ? "right" : "left";
      if (idx === 8 && r.isBlocked) {
        doc.fillColor("#DC2626").font("Helvetica-Bold");
      } else {
        doc.fillColor("#1F2937").font("Helvetica");
      }
      doc.text(val, currentX + 2, currentY + 4, {
        width: w - 4,
        align: align as any,
        lineBreak: false,
        ellipsis: true,
      });
      currentX += w;
    });

    currentY += rowHeight;
  });

  // Footer Signatures
  if (currentY > pageHeight - bottomMargin - 50) {
    doc.addPage({ size: "A4", layout: "landscape" });
    currentY = topMargin + 20;
  } else {
    currentY += 15;
  }

  doc.fontSize(8.5).font("Helvetica-Bold").fillColor("#111827");
  doc.text("Prepared By: ___________________________", leftMargin + 40, currentY);
  doc.text("Approved By: ___________________________", leftMargin + 500, currentY);

  doc
    .fontSize(7.5)
    .font("Helvetica")
    .fillColor("#6B7280")
    .text(
      `Reporting Month: ${meta.reportingMonth}  |  Generated by: ${meta.generatedBy} on ${meta.generatedAt}`,
      leftMargin,
      currentY + 22,
      { align: "center", width: contentWidth }
    );
}

/**
 * Builds Autoclave Log Book (Sterilization) PDF stream.
 */
export function buildAutoclavePdf(
  doc: PDFKit.PDFDocument,
  rows: AutoclaveExportRow[],
  equip: EquipmentExportInfo,
  meta: ExportMetadata
): void {
  const pageWidth = 841.89; // A4 Landscape
  const pageHeight = 595.28;
  const leftMargin = 30;
  const topMargin = 25;
  const rightMargin = 30;
  const bottomMargin = 40;
  const contentWidth = pageWidth - leftMargin - rightMargin;

  const renderHeader = () => {
    // Left title
    doc
      .fontSize(12)
      .font("Helvetica-Bold")
      .fillColor("#111827")
      .text("PETLAD MAHAL AROGYA MANDAL PHARMACY, Piplata", leftMargin, topMargin);
    doc
      .fontSize(10)
      .font("Helvetica-Bold")
      .fillColor("#1E3A8A")
      .text("Autoclave Log Book (Sterilization)", leftMargin, topMargin + 15);
    doc
      .fontSize(8.5)
      .font("Helvetica")
      .fillColor("#4B5563")
      .text(`Reporting Month: ${meta.reportingMonth}`, leftMargin, topMargin + 28);

    // Right equipment info box
    const boxWidth = 200;
    const boxX = pageWidth - rightMargin - boxWidth;
    doc.rect(boxX, topMargin, boxWidth, 38).fillAndStroke("#F9FAFB", "#D1D5DB");
    doc.fontSize(7.5).font("Helvetica-Bold").fillColor("#1F2937");
    doc.text(`Format No.: ${equip.formatNo}`, boxX + 6, topMargin + 4);
    doc.text(`Ref. SOP No.: ${equip.refSopNo}`, boxX + 6, topMargin + 15);
    doc.text(`Equipment No.: ${equip.equipmentNo}`, boxX + 6, topMargin + 26);
  };

  const colWidths = [55, 155, 58, 62, 58, 55, 62, 135, 75, 66];

  const renderTableHeaders = (y: number) => {
    // Header tier 1 (y, height 14)
    doc.rect(leftMargin, y, contentWidth, 26).fill("#1E3A8A");
    doc.fontSize(7.5).font("Helvetica-Bold").fillColor("#FFFFFF");

    let curX = leftMargin;
    doc.text("Date", curX + 2, y + 8, { width: colWidths[0] - 4, align: "center" });
    curX += colWidths[0];

    doc.text("Name of Cycle Load", curX + 2, y + 8, { width: colWidths[1] - 4, align: "left" });
    curX += colWidths[1];

    doc.text("Autoclave Start", curX + 2, y + 8, { width: colWidths[2] - 4, align: "center" });
    curX += colWidths[2];

    // Sterilization spans 4 sub-columns
    const sterWidth = colWidths[3] + colWidths[4] + colWidths[5] + colWidths[6];
    doc.text("Sterilization", curX, y + 2, { width: sterWidth, align: "center" });

    // Sub-columns
    doc.fontSize(7);
    doc.text("Start Time", curX + 2, y + 14, { width: colWidths[3] - 4, align: "center" });
    doc.text("Temp", curX + colWidths[3] + 2, y + 14, { width: colWidths[4] - 4, align: "center" });
    doc.text("Pressure", curX + colWidths[3] + colWidths[4] + 2, y + 14, {
      width: colWidths[5] - 4,
      align: "center",
    });
    doc.text("End Time", curX + colWidths[3] + colWidths[4] + colWidths[5] + 2, y + 14, {
      width: colWidths[6] - 4,
      align: "center",
    });
    curX += sterWidth;

    doc.fontSize(7.5);
    doc.text("Cleaning (weekly)", curX + 2, y + 8, { width: colWidths[7] - 4, align: "left" });
    curX += colWidths[7];

    doc.text("Done by", curX + 2, y + 8, { width: colWidths[8] - 4, align: "center" });
    curX += colWidths[8];

    doc.text("Verification", curX + 2, y + 8, { width: colWidths[9] - 4, align: "center" });
  };

  renderHeader();
  let currentY = topMargin + 48;
  renderTableHeaders(currentY);
  currentY += 26;

  rows.forEach((r) => {
    const isVerified = r.verificationStatus === "Verified";
    const rowHeight = isVerified ? 24 : 17;

    if (currentY + rowHeight > pageHeight - bottomMargin - 45) {
      doc.addPage({ size: "A4", layout: "landscape" });
      renderHeader();
      currentY = topMargin + 48;
      renderTableHeaders(currentY);
      currentY += 26;
    }

    doc.rect(leftMargin, currentY, contentWidth, rowHeight).strokeColor("#E5E7EB").stroke();

    let curX = leftMargin;
    doc.fontSize(7).font("Helvetica").fillColor("#111827");

    // 0 Date
    doc.text(r.date, curX + 2, currentY + 4, { width: colWidths[0] - 4, align: "center" });
    curX += colWidths[0];

    // 1 Load Name
    doc.text(r.cycleLoadName, curX + 2, currentY + 4, { width: colWidths[1] - 4 });
    curX += colWidths[1];

    // 2 Autoclave start
    doc.text(r.autoclaveStartTime, curX + 2, currentY + 4, {
      width: colWidths[2] - 4,
      align: "center",
    });
    curX += colWidths[2];

    // 3 Ster start
    let sterStartText = r.sterilizationStartTime;
    if (isVerified && r.actualStartTime) sterStartText += `\nAct: ${r.actualStartTime}`;
    doc.text(sterStartText, curX + 2, currentY + 3, {
      width: colWidths[3] - 4,
      align: "center",
    });
    curX += colWidths[3];

    // 4 Temp
    let tempText = r.temperatureC;
    if (isVerified && r.actualTemperatureC) tempText += `\nAct: ${r.actualTemperatureC}`;
    doc.text(tempText, curX + 2, currentY + 3, {
      width: colWidths[4] - 4,
      align: "center",
    });
    curX += colWidths[4];

    // 5 Pressure
    let pressText = r.pressure;
    if (isVerified && r.actualPressure) pressText += `\nAct: ${r.actualPressure}`;
    doc.text(pressText, curX + 2, currentY + 3, {
      width: colWidths[5] - 4,
      align: "center",
    });
    curX += colWidths[5];

    // 6 End time
    let endText = r.endTime;
    if (isVerified && r.actualEndTime) endText += `\nAct: ${r.actualEndTime}`;
    doc.text(endText, curX + 2, currentY + 3, {
      width: colWidths[6] - 4,
      align: "center",
    });
    curX += colWidths[6];

    // 7 Cleaning
    doc.text(r.cleaningWeekly, curX + 2, currentY + 4, { width: colWidths[7] - 4 });
    curX += colWidths[7];

    // 8 Done By
    doc.text(r.doneBy, curX + 2, currentY + 4, {
      width: colWidths[8] - 4,
      align: "center",
      ellipsis: true,
    });
    curX += colWidths[8];

    // 9 Verification badge
    const vStatus = r.verificationStatus;
    if (vStatus === "Verified") {
      doc.fillColor("#047857").font("Helvetica-Bold");
    } else if (vStatus === "Pending verification") {
      doc.fillColor("#1D4ED8").font("Helvetica-Bold");
    } else {
      doc.fillColor("#4B5563").font("Helvetica");
    }
    doc.text(vStatus, curX + 2, currentY + 4, { width: colWidths[9] - 4, align: "center" });

    currentY += rowHeight;
  });

  // Footnote and Signatures
  if (currentY > pageHeight - bottomMargin - 50) {
    doc.addPage({ size: "A4", layout: "landscape" });
    currentY = topMargin + 20;
  } else {
    currentY += 10;
  }

  doc
    .fontSize(7)
    .font("Helvetica-Oblique")
    .fillColor("#4B5563")
    .text(
      "Values marked Planned are laboratory defaults entered in advance and are not verified operating records. Only entries marked Verified have verified readings.",
      leftMargin,
      currentY,
      { width: contentWidth }
    );

  currentY += 16;
  doc.fontSize(8).font("Helvetica-Bold").fillColor("#111827");
  doc.text("Done By: ___________________________", leftMargin + 40, currentY);
  doc.text("Checked By: ___________________________", leftMargin + 500, currentY);

  doc
    .fontSize(7)
    .font("Helvetica")
    .fillColor("#6B7280")
    .text(
      `Reporting Month: ${meta.reportingMonth}  |  Generated by: ${meta.generatedBy} on ${meta.generatedAt}`,
      leftMargin,
      currentY + 20,
      { align: "center", width: contentWidth }
    );
}

/**
 * Builds the Combined Monthly Package PDF containing Media Preparation Record followed by Autoclave Log Book.
 */
export function buildCombinedPackagePdf(
  mediaRows: MediaExportRow[],
  autoclaveRows: AutoclaveExportRow[],
  equip: EquipmentExportInfo,
  meta: ExportMetadata
): PDFKit.PDFDocument {
  const doc = new PDFDocument({
    size: "A4",
    layout: "landscape",
    autoFirstPage: true,
    bufferPages: true,
  });

  // Section 1: Media Preparation Record
  buildMediaPdf(doc, mediaRows, meta);

  // Section 2: Autoclave Log Book
  doc.addPage({ size: "A4", layout: "landscape" });
  buildAutoclavePdf(doc, autoclaveRows, equip, meta);

  // Add continuous page numbers "Page X of Y" across all buffered pages
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc
      .fontSize(7.5)
      .font("Helvetica")
      .fillColor("#9CA3AF")
      .text(`Page ${i + 1} of ${range.count}`, 841.89 - 30 - 100, 595.28 - 25, {
        width: 100,
        align: "right",
      });
  }

  return doc;
}
